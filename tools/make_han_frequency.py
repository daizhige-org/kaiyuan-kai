#!/usr/bin/env python3
"""Regenerate data/han-frequency.txt from jieba's dict.txt.

build.py orders Han characters by how often they occur, so that the common
ones share a few webfont slices. The ranking comes from jieba's word
frequency dictionary (https://github.com/fxsjy/jieba, MIT): each word's count
is added to every Han character in it. Only the resulting character order is
kept in this repo, not the 5 MB dictionary.

Usage:
    curl -LO https://raw.githubusercontent.com/fxsjy/jieba/master/jieba/dict.txt
    python3 tools/make_han_frequency.py dict.txt
"""

import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "data" / "han-frequency.txt"
PER_LINE = 50

HEADER = """\
# Han characters, most frequent first. Generated by
# tools/make_han_frequency.py; do not edit by hand.
#
# Derived from the word frequencies in jieba's dict.txt
# (https://github.com/fxsjy/jieba), Copyright (c) 2013 Sun Junyi, MIT License.
# Each word's count is added to every Han character it contains; ties are
# broken by GB2312 level, then codepoint.
"""


def is_cjk_ideograph(cp: int) -> bool:
    return (
        0x3400 <= cp <= 0x4DBF
        or 0x4E00 <= cp <= 0x9FFF
        or 0xF900 <= cp <= 0xFAFF
        or 0x20000 <= cp <= 0x323AF
    )


def gb2312_tier(cp: int) -> int:
    """1 for GB2312 level 1 (3,755 common characters), 2 for level 2, else 3."""
    try:
        b = chr(cp).encode("gb2312")
    except UnicodeEncodeError:
        return 3
    if len(b) == 2:
        if 0xB0 <= b[0] <= 0xD7:
            return 1
        if 0xD8 <= b[0] <= 0xF7:
            return 2
    return 3


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    freq: dict[int, int] = {}
    with open(sys.argv[1], encoding="utf-8", errors="ignore") as f:
        for line in f:
            parts = line.split()
            if len(parts) < 2 or not parts[1].isdigit():
                continue
            for ch in parts[0]:
                cp = ord(ch)
                if is_cjk_ideograph(cp):
                    freq[cp] = freq.get(cp, 0) + int(parts[1])
    ranked = sorted(freq, key=lambda cp: (-freq[cp], gb2312_tier(cp), cp))
    chars = "".join(map(chr, ranked))
    lines = [chars[i : i + PER_LINE] for i in range(0, len(chars), PER_LINE)]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(HEADER + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT}: {len(ranked):,} characters")


if __name__ == "__main__":
    main()
